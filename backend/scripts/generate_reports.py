def table(headers, rows, right=()):
    """Markdown table. `right` lists the column indexes to right-align."""
    sep = ["---:" if i in right else ":---" for i in range(len(headers))]
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join(sep) + " |"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def num(value, digits=2):
    return f"{value:,.{digits}f}"


# --------------------------------------------------------------------------- EDA
def build_eda(trips) -> str:
    df = pl.DataFrame(trips).with_columns(
        pl.col("pickup_datetime").str.to_datetime(),
        pl.col("dropoff_datetime").str.to_datetime(),
    ).with_columns(
        ((pl.col("dropoff_datetime") - pl.col("pickup_datetime")).dt.total_seconds() / 60).alias("duration_min"),
    ).with_columns(
        pl.when(pl.col("duration_min") > 0)
        .then(pl.col("trip_distance") / (pl.col("duration_min") / 60))
        .otherwise(0.0).alias("speed_mph"),
    )
    n = df.height
    first, last = df["pickup_datetime"].min(), df["pickup_datetime"].max()

    nulls = df.null_count().row(0)
    null_rows = [(c, f"{v:,}") for c, v in zip(df.columns, nulls) if c not in ("duration_min", "speed_mph")]

    key = ["pickup_datetime", "dropoff_datetime", "pickup_location_id", "dropoff_location_id", "fare_amount"]
    duplicates = n - df.select(key).unique().height

    numeric = ["trip_distance", "duration_min", "speed_mph", "fare_amount", "tip_amount", "total_amount", "passenger_count"]
    units = {"trip_distance": "miles", "duration_min": "minutes", "speed_mph": "mph", "fare_amount": "$",
             "tip_amount": "$", "total_amount": "$", "passenger_count": "people"}
    numeric_rows = []
    for col in numeric:
        s = df[col]
        numeric_rows.append((f"`{col}` ({units[col]})", num(s.min()), num(s.quantile(0.05)), num(s.median()),
                             num(s.mean()), num(s.quantile(0.95)), num(s.max())))

    # The same rules the Silver validation applies (app/services/data_cleaner.py)
    rules = [
        ("temporal_sequence", "drop-off is not after pickup", pl.col("dropoff_datetime") <= pl.col("pickup_datetime")),
        ("duration_range", "duration outside 1 to 240 minutes", (pl.col("duration_min") < 1) | (pl.col("duration_min") > 240)),
        ("distance_range", "distance outside 0 to 150 miles", (pl.col("trip_distance") <= 0) | (pl.col("trip_distance") > 150)),
        ("fare_range", "fare outside $2.50 to $600", (pl.col("fare_amount") < 2.5) | (pl.col("fare_amount") > 600)),
        ("speed_limit", "average speed above 85 mph", pl.col("speed_mph") > 85),
        ("passenger_count", "passengers outside 1 to 9", (pl.col("passenger_count") < 1) | (pl.col("passenger_count") > 9)),
    ]
    rule_rows = []
    any_bad = pl.lit(False)
    for name, text, expr in rules:
        bad = df.filter(expr).height
        any_bad = any_bad | expr
        rule_rows.append((f"`{name}`", text, f"{bad:,}", f"{bad / n * 100:.2f}%"))
    rejected = df.filter(any_bad).height

    by_hour = (df.group_by(pl.col("pickup_datetime").dt.hour().alias("hour"))
               .agg(pl.len().alias("trips"), pl.col("fare_amount").mean().alias("fare")).sort("hour"))
    days = df.select(pl.col("pickup_datetime").dt.date().n_unique()).item()
    peak = by_hour["trips"].max()
    hour_rows = [(f"{r['hour']:02d}:00", f"{r['trips']:,}", num(r["trips"] / days, 1), num(r["fare"]),
                  "█" * max(1, round(r["trips"] / peak * 24))) for r in by_hour.iter_rows(named=True)]

    by_day = (df.group_by(pl.col("pickup_datetime").dt.date().alias("day"))
              .agg(pl.len().alias("trips"), pl.col("total_amount").sum().alias("revenue")).sort("day"))
    day_rows = [(str(r["day"]), r["day"].strftime("%A"), f"{r['trips']:,}", "$" + num(r["revenue"], 0))
                for r in by_day.iter_rows(named=True)]

    by_zone = (df.group_by("pickup_location_id")
               .agg(pl.len().alias("trips"), pl.col("fare_amount").mean().alias("fare"),
                    pl.col("trip_distance").mean().alias("dist"))
               .sort("trips", descending=True))
    zone_rows = [(ZONE_NAMES.get(r["pickup_location_id"], f"Zone {r['pickup_location_id']}"), f"{r['trips']:,}",
                  f"{r['trips'] / n * 100:.1f}%", "$" + num(r["fare"]), num(r["dist"]))
                 for r in by_zone.iter_rows(named=True)]

    by_pay = (df.group_by("payment_type")
              .agg(pl.len().alias("trips"), pl.col("tip_amount").mean().alias("tip")).sort("trips", descending=True))
    pay_rows = [(r["payment_type"], f"{r['trips']:,}", f"{r['trips'] / n * 100:.1f}%", "$" + num(r["tip"]))
                for r in by_pay.iter_rows(named=True)]

    quality_note = (
        f"Validation must run before aggregation: {rejected / n * 100:.1f}% of rows would otherwise distort Gold averages."
        if rejected else
        "The generated sample is clean: no row breaks a validation rule and there are no duplicates. The rules and the "
        "duplicate check therefore only fire on replays (every repeated event is skipped) and on bad input sent to the API."
    )
    busiest, quietest = by_hour.sort("trips", descending=True).row(0, named=True), by_hour.sort("trips").row(0, named=True)
    top_zone = zone_rows[0]

    return f"""# Hailcast: exploratory data analysis

{HEADER.format(stamp=STAMP)}
Profiled with Polars from `backend/app/data/sample_trips.json`.

## 1. Shape

- **{n:,} trips**, {len(trips[0])} columns, {by_zone.height} pickup zones, {by_pay.height} payment types.
- Pickups run from **{first:%Y-%m-%d %H:%M}** to **{last:%Y-%m-%d %H:%M}** ({days} calendar days).
- Exact duplicates on the event key (pickup time, drop-off time, both zones, fare): **{duplicates:,}**.

## 2. Missing values

{table(["Column", "Nulls"], null_rows, right=(1,))}

## 3. Numeric columns

`duration_min` and `speed_mph` are derived from the timestamps and the distance.

{table(["Column", "Min", "5th pct", "Median", "Mean", "95th pct", "Max"], numeric_rows, right=(1, 2, 3, 4, 5, 6))}

## 4. Rows the validation rules reject

These are the rules the Silver step applies. A row can break more than one rule.
**{rejected:,} of {n:,} rows ({rejected / n * 100:.2f}%) break at least one** and stay in Bronze only.

{table(["Rule", "Meaning", "Rows", "Share"], rule_rows, right=(2, 3))}

## 5. Demand by hour of day

Busiest hour is {busiest['hour']:02d}:00 ({busiest['trips']:,} trips over {days} days); quietest is
{quietest['hour']:02d}:00 ({quietest['trips']:,}). This daily cycle is why the forecaster uses hour-of-day
and 24-hour-lag features.

{table(["Hour", "Trips", "Per day", "Average fare ($)", "Shape"], hour_rows, right=(1, 2, 3))}

## 6. Demand by day

The first and last days can be partial.

{table(["Date", "Weekday", "Trips", "Revenue"], day_rows, right=(2, 3))}

## 7. Pickup zones

{top_zone[0]} has the most pickups ({top_zone[1]}, {top_zone[2]} of all trips).

{table(["Zone", "Trips", "Share", "Average fare", "Average distance (mi)"], zone_rows, right=(1, 2, 3, 4))}

## 8. Payment types

{table(["Payment type", "Trips", "Share", "Average tip"], pay_rows, right=(1, 2, 3))}

## 9. What this means for the pipeline

- The sample covers only {days} days, so weekly patterns cannot be learned from it and forecast
  metrics come from few test hours. Treat the evaluation as a demonstration of method.
- {quality_note}
- Because the generator is seeded, this report is reproducible byte for byte apart from the timestamp.
"""


# ------------------------------------------------------------------- evaluation
async def build_ml(trips) -> str:
    await init_db()
    result = await ETLPipeline.run_batch_ingestion(trips, source_name="report_run")
    async with AsyncSessionLocal() as session:
        raw = (await session.execute(select(func.count(RawTrip.id)))).scalar_one()
        silver = (await session.execute(select(func.count(SilverTrip.id)))).scalar_one()
        gold = (await session.execute(select(GoldHourlyDemand).order_by(GoldHourlyDemand.time_bucket))).scalars().all()
    await engine.dispose()

    frame = pd.DataFrame([{
        "time_bucket": g.time_bucket, "location_id": g.location_id, "trip_count": g.trip_count,
        "avg_fare": g.avg_fare, "avg_distance": g.avg_distance, "total_revenue": g.total_revenue,
        "avg_duration_minutes": g.avg_duration_minutes,
    } for g in gold])
    hourly = to_citywide_hourly(frame)
    out = train_and_evaluate(frame)
    metrics = {m["model_name"]: m for m in out["metrics"]}
    best = out["best_model"]
    lgb, persist = metrics["LightGBM_Forecaster"], metrics["Baseline_Persistence"]

    metric_rows = [(f"**{MODEL_LABELS[k]}**" if k == best else MODEL_LABELS[k], num(m["mae"]), num(m["rmse"]),
                    f"{m['mape']:.1f}%", f"{m['r2_score']:.3f}") for k, m in metrics.items()]
    fold_rows = [(f["fold"], f"{f['train_start'][:16]} to {f['train_end'][:16]}", f["train_hours"],
                  f"{f['test_start'][:16]} to {f['test_end'][:16]}", f["test_hours"],
                  *(num(f["mae"][k]) for k in MODEL_LABELS)) for f in out["folds"]]
    leak_ok = all(f["train_end"] < f["test_start"] for f in out["folds"])
    importances = sorted(out["feature_importances"].items(), key=lambda kv: kv[1], reverse=True)[:10] \
        if isinstance(out["feature_importances"], dict) else \
        [(i.get("feature"), i.get("importance")) for i in out["feature_importances"][:10]]
    imp_total = sum(v for _, v in importances) or 1
    whole = all(float(v).is_integer() for _, v in importances)
    imp_rows = [(f"`{name}`", f"{value:,.0f}" if whole else f"{value:.3f}", f"{value / imp_total * 100:.0f}%")
                for name, value in importances]

    if best == "LightGBM_Forecaster":
        gain = (persist["mae"] - lgb["mae"]) / persist["mae"] * 100
        verdict = (f"LightGBM has the lowest error: on average it misses by {num(lgb['mae'])} trips per hour, "
                   f"{gain:.0f}% less than repeating the previous hour ({num(persist['mae'])}).")
    else:
        verdict = (f"A baseline wins on this data: **{MODEL_LABELS[best]}** misses by {num(metrics[best]['mae'])} trips "
                   f"per hour, LightGBM by {num(lgb['mae'])}. With this little history the simple rule is the better forecast.")

    return f"""# Hailcast: forecasting evaluation

{HEADER.format(stamp=STAMP)}
## 1. What is forecast

City-wide taxi pickups per hour (all zones summed), one hour ahead. Zone-level numbers in the
dashboard split that city-wide forecast by each zone's historical share for the hour of day.

## 2. Data used in this run

- {result['total_received']:,} sample trips loaded through the batch pipeline: {raw:,} stored in Bronze,
  {silver:,} passed validation into Silver, {len(gold):,} zone-hour rows in Gold.
- {len(hourly):,} complete city-wide hours from {hourly['time_bucket'].min():%Y-%m-%d %H:%M} to
  {hourly['time_bucket'].max():%Y-%m-%d %H:%M}. The newest hour is dropped because it may still be filling.
- {out['hours_used']:,} hours remain after building lag features.

## 3. How leakage is prevented

1. **Walk-forward splits.** `TimeSeriesSplit(n_splits=3)`: each fold trains on an expanding window and
   tests on the hours that follow it. Rows are never shuffled.
   Check on this run, every training window ends before its test window starts: **{'yes' if leak_ok else 'NO'}**.
2. **Past-only features.** Every lag and rolling mean is shifted by at least one hour, so the value
   being predicted is never an input. `backend/tests/test_reliability.py::test_features_never_use_the_future`
   changes future demand and asserts that no earlier feature moves.
3. **Baselines get the same folds.** The hour-of-day average is fitted on the training window only.

## 4. Results

Mean over the three test windows. Lower MAE, RMSE and MAPE are better; higher R² is better.

{table(["Model", "MAE (trips/hour)", "RMSE", "MAPE", "R²"], metric_rows, right=(1, 2, 3, 4))}

{verdict}

### Per fold

{table(["Fold", "Train window", "Train hours", "Test window", "Test hours", "MAE: previous hour", "MAE: hour average", "MAE: LightGBM"], fold_rows, right=(2, 4, 5, 6, 7))}

## 5. What the model leans on

LightGBM feature importance for the final model trained on all hours (top 10).

{table(["Feature", "Importance", "Share of top 10"], imp_rows, right=(1, 2))}

## 6. Limits

- The data is synthetic and covers about {len(hourly) / 24:.1f} days, so each test window is only
  {out['folds'][-1]['test_hours']} hours. The numbers show the method works end to end; they are not evidence
  about real New York demand.
- No weekly seasonality can be learned from less than two weeks of data.
- Accuracy is measured one hour ahead. The dashboard's multi-hour forecast feeds its own predictions
  back in, so error grows with the horizon; the shaded band there uses 1.28 x RMSE as a rough 80% range.
- MAPE is unstable in quiet night hours where actual demand is close to zero.

## 7. Reproduce

```bash
python backend/scripts/generate_reports.py   # rewrites this file and docs/eda_report.md
python -m pytest                             # leakage, pipeline and reliability tests
```

In the running app, `POST /api/v1/ml/train` runs the same evaluation on whatever is in the Gold table
and appends the result to `backend/app/ml/saved_models/experiments_registry.json`.
"""


def main():
    if not SAMPLE.exists():
        from app.data.download_sample import generate_sample_dataset
        generate_sample_dataset(SAMPLE)
    with open(SAMPLE, "r", encoding="utf-8") as f:
        trips = json.load(f)

    DOCS.mkdir(exist_ok=True)
    (DOCS / "eda_report.md").write_text(build_eda(trips), encoding="utf-8")
    print("wrote docs/eda_report.md")
    (DOCS / "ml_evaluation_report.md").write_text(asyncio.run(build_ml(trips)), encoding="utf-8")
    print("wrote docs/ml_evaluation_report.md")


if __name__ == "__main__":
    main()
